export const DICT: Record<Lang, Dict> = { en, hi };
export const t = (lang: Lang) => DICT[lang];

/** 24-hour "HH:MM" → "7:00 AM" / "सुबह 7:00". */
export function clock(hhmm: string, lang: Lang): string {
  const [h, m] = hhmm.split(":").map(Number);
  const h12 = ((h + 11) % 12) + 1;
  if (lang === "hi") {
    const part = h < 12 ? "सुबह" : h < 16 ? "दोपहर" : h < 20 ? "शाम" : "रात";
    return `${part} ${h12}:${String(m).padStart(2, "0")}`;
  }
  return `${h12}:${String(m).padStart(2, "0")} ${h < 12 ? "AM" : "PM"}`;
}

export const rupees = (minor: number) =>
  "₹" + (minor / 100).toLocaleString("en-IN", { maximumFractionDigits: 2, minimumFractionDigits: 0 });
