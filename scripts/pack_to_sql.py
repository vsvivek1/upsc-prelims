#!/usr/bin/env python3
"""Turns content/upsc_prelims.json into SQL that upserts topics, cards and
questions into the upsc schema.

Usage: python3 scripts/pack_to_sql.py [pack.json] > supabase/seed/content.sql

Cards and questions not in the pack are deleted, so the database always matches
the pack. Learner progress (card_state, review_log) keeps rows for cards that
still exist; a card is never renamed once published.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CARD_COLUMNS = {"id", "topic", "type", "seq", "difficulty", "status"}


def lit(value):
    """A SQL literal using dollar quoting, safe for any text."""
    s = value if isinstance(value, str) else json.dumps(value, ensure_ascii=False)
    tag = "$j$"
    while tag in s:
        tag = tag[:-1] + "x$"
    return f"{tag}{s}{tag}"


def arr(items):
    return "array[" + ",".join(lit(i) for i in items) + "]::text[]" if items else "'{}'::text[]"


def main():
    path = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "content" / "upsc_prelims.json"
    pack = json.loads(path.read_text())
    version = pack.get("schema_version", "1.0") + "+" + str(len(pack["cards"]))
    freq = {t["id"]: t.get("freq", 0.5) for t in pack["topics"]}
    seq = {c["id"]: c["seq"] for c in pack["cards"]}

    out = ["-- Generated by scripts/pack_to_sql.py. Do not edit by hand.", "begin;"]

    for t in pack["topics"]:
        out.append(
            "insert into upsc.topics (id, subject, title, ord, freq, prereq) values ("
            f"{lit(t['id'])}, {lit(t['subject'])}, {lit(t['title'])}::jsonb, {int(t['order'])}, {float(t['freq'])}, {arr(t.get('prereq', []))})"
            " on conflict (id) do update set subject = excluded.subject, title = excluded.title,"
            " ord = excluded.ord, freq = excluded.freq, prereq = excluded.prereq;"
        )

    # seq is unique: move existing rows out of the way before writing new numbers.
    out.append("update upsc.cards set seq = -seq - 100000;")
    for c in pack["cards"]:
        payload = {k: v for k, v in c.items() if k not in CARD_COLUMNS}
        out.append(
            "insert into upsc.cards (id, topic, type, seq, difficulty, freq, status, payload, pack_version) values ("
            f"{lit(c['id'])}, {lit(c['topic'])}, {lit(c['type'])}, {int(c['seq'])}, {int(c['difficulty'])}, "
            f"{float(freq.get(c['topic'], 0.5))}, {lit(c.get('status', 'needs_review'))}, {lit(payload)}::jsonb, {lit(version)})"
            " on conflict (id) do update set topic = excluded.topic, type = excluded.type, seq = excluded.seq,"
            " difficulty = excluded.difficulty, freq = excluded.freq, status = excluded.status,"
            " payload = excluded.payload, pack_version = excluded.pack_version, updated_at = now();"
        )
    ids = ",".join(lit(c["id"]) for c in pack["cards"])
    out.append(f"delete from upsc.cards where id not in ({ids});")

    for q in pack["questions"]:
        payload = {k: q[k] for k in ("kind", "q", "options", "answer", "explain") if k in q}
        qseq = max((seq.get(cid, 0) for cid in q["covers"]), default=0)
        out.append(
            "insert into upsc.questions (id, topic, seq, covers, source, year, payload) values ("
            f"{lit(q['id'])}, {lit(q['topic'])}, {qseq}, {arr(q['covers'])}, {lit(q['source'])}, "
            f"{int(q['year']) if q.get('year') else 'null'}, {lit(payload)}::jsonb)"
            " on conflict (id) do update set topic = excluded.topic, seq = excluded.seq, covers = excluded.covers,"
            " source = excluded.source, year = excluded.year, payload = excluded.payload;"
        )
    qids = ",".join(lit(q["id"]) for q in pack["questions"])
    out.append(f"delete from upsc.questions where id not in ({qids});")
    out.append("commit;")
    print("\n".join(out))


if __name__ == "__main__":
    main()
